"""Literature synthesis workflow (RF-016).

Builds a literature-review DRAFT from APPROVED RF-015 extraction records.
No manuscript drafting (RF-018) and no automatic conclusion approval.

Safeguards:
- Eligibility: only extraction records with review == APPROVED contribute
  evidence. PENDING/REJECTED, missing or corrupt records are listed under
  `eligibility.excluded` with a reason and never appear as findings.
- Traceability: every evidence entry carries its `source_id` and a stable
  derived `extraction_id` (EXT-<same id body as the source>) — extraction
  is 1:1 with a source by design. Text is copied verbatim from the
  extraction record; nothing is paraphrased or invented, and citations
  are source IDs only (never fabricated paper metadata).
- Insufficient evidence: fewer than MINIMUM_SOURCES approved extractions
  (or no approved evidence at all) sets `insufficient_evidence` with an
  explicit reason; the draft is still written for inspection but is
  marked as insufficient — never padded.
- Evidence vs interpretation: `evidence` holds verbatim source material
  only. `interpretation` (agreements, contradictions, limitations,
  unanswered questions) is a separate section that is NOT GENERATED by
  the deterministic draft and is labelled AI-GENERATED + PENDING HUMAN
  REVIEW if add_ai_interpretation() is explicitly invoked. Nothing in
  either section is auto-approved.
- Governance: the draft starts review="PENDING HUMAN REVIEW";
  approve_synthesis() records an explicit human decision, and an APPROVED
  draft cannot be overwritten.

AI usage is optional (RF-016 does not require it). When requested it goes
through RF-014's run_generation(), which records usage/errors in
logs/usage.jsonl and re-raises provider failures — handled here as an
explicit FAILED interpretation, never a crash and never fabricated text.
No live call is made by any test.
"""
import json
import os
from datetime import datetime, timezone
from pathlib import Path

from app.core import approvals
from app.core.sources import SourceError, load_manifest
from app.core.usage_log import run_generation
from app.providers.contracts import ProviderRequest
from app.providers.errors import ProviderError
from app.workflows.paper_extraction import (OUTCOME_COMPLETED, REVIEW_APPROVED,
                                            REVIEW_PENDING, load_extraction)

DRAFT_RELPATH = "outputs/drafts/literature_review_draft.json"
MINIMUM_SOURCES = 2
TASK = "literature_synthesis"
REVIEW_REJECTED = "REJECTED"


class SynthesisError(SourceError):
    """Synthesis refused/invalid (reuses the RF-010 error hierarchy)."""


def draft_path(root: Path) -> Path:
    return root / DRAFT_RELPATH


def _now() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="seconds")


def _extraction_id(source_id: str) -> str:
    """Stable, provenance-preserving ID: extraction is 1:1 with a source."""
    return "EXT-" + source_id.removeprefix("SRC-")


def _entry(item: dict, source_id: str) -> dict:
    return {"text": item["text"], "source_id": source_id,
            "extraction_id": _extraction_id(source_id),
            "candidate_id": item.get("extraction_id"),
            "classification": item.get("classification"),
            "section": item.get("section"),
            "page": item.get("page")}


def collect_evidence(root: Path):
    """Return (evidence entries by kind, eligibility dict).

    Eligible items: all non-rejected candidates from a whole-record
    APPROVED extraction, plus individually APPROVED candidates from a
    record that is still PENDING. Individually REJECTED candidates never
    contribute. Everything else is explicitly excluded."""
    manifest = load_manifest(root)
    eligible, excluded = [], []
    by_kind = {"findings": [], "claims": [], "methods": [],
               "other_evidence": []}
    section = {"finding": "findings", "claim": "claims", "method": "methods"}
    for source_id in sorted(manifest["sources"]):
        record = None
        try:
            record = load_extraction(root, source_id)
        except SynthesisError:
            raise
        except SourceError as exc:
            excluded.append({"source_id": source_id,
                             "reason": f"unreadable extraction record: {exc}"})
            continue
        if record is None:
            excluded.append({"source_id": source_id,
                             "reason": "not extracted (no extraction record)"})
            continue
        record_approved = record.get("review") == REVIEW_APPROVED
        items = [item for item in record.get("items", [])
                 if isinstance(item, dict) and isinstance(item.get("text"), str)]
        eligible_items = [item for item in items
                          if item.get("decision") != REVIEW_REJECTED
                          and (record_approved
                               or item.get("decision") == REVIEW_APPROVED)]
        if not eligible_items:
            if record.get("outcome") != OUTCOME_COMPLETED:
                reason = (f"extraction outcome is "
                          f"{record.get('outcome')!r}; no evidence items "
                          "available")
            elif record_approved:
                reason = "approved extraction contains no evidence items"
            else:
                reason = (f"extraction review is {record.get('review')!r} "
                          "and no candidates are individually approved")
            excluded.append({"source_id": source_id, "reason": reason})
            continue
        eligible.append(source_id)
        for item in eligible_items:
            by_kind[section.get(item.get("kind"), "other_evidence")].append(
                _entry(item, source_id))
    eligibility = {
        "sources_in_manifest": len(manifest["sources"]),
        "approved_extractions": eligible,
        "excluded": excluded,
        "minimum_sources": MINIMUM_SOURCES,
        "insufficient_evidence": len(eligible) < MINIMUM_SOURCES,
        "insufficient_reason": None if len(eligible) >= MINIMUM_SOURCES else
        (f"{len(eligible)} approved extraction(s) available; synthesis "
         f"requires at least {MINIMUM_SOURCES} independent sources"),
    }
    return by_kind, eligibility


def build_draft(root: Path) -> dict:
    """Deterministic draft: verbatim approved evidence, no interpretation."""
    evidence, eligibility = collect_evidence(root)
    return {
        "document": "literature_review_draft",
        "version": 1,
        "status": "DRAFT",
        "review": REVIEW_PENDING,
        "reviewed_by": None,
        "reviewed_at": None,
        "generated_at": _now(),
        "eligibility": eligibility,
        "evidence": evidence,   # source material only, never AI text
        "interpretation": {     # separated by design; never auto-approved
            "status": "NOT GENERATED",
            "origin": None,
            "provider": None,
            "model": None,
            "agreements": [],
            "contradictions": [],
            "limitations": [],
            "unanswered_questions": [],
            "review": REVIEW_PENDING,
            "error": None,
            "note": "Deterministic drafts contain no interpretation. "
                    "Agreements/contradictions/limitations/unanswered "
                    "questions require explicit AI interpretation or human "
                    "review and are never inferred by this workflow.",
        },
    }


def _write(root: Path, draft: dict) -> None:
    path = draft_path(root)
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(path.name + ".tmp")
    tmp.write_text(json.dumps(draft, indent=2, ensure_ascii=False),
                   encoding="utf-8")
    os.replace(tmp, path)


def load_draft(root: Path) -> dict | None:
    path = draft_path(root)
    if not path.is_file():
        return None
    try:
        draft = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, UnicodeDecodeError, json.JSONDecodeError) as exc:
        raise SynthesisError(f"synthesis draft unreadable: {exc}") from exc
    if not isinstance(draft, dict) or "evidence" not in draft:
        raise SynthesisError("synthesis draft malformed")
    return draft


def save_draft(root: Path, draft: dict) -> dict:
    existing = load_draft(root)
    if existing is not None and existing.get("review") == REVIEW_APPROVED:
        raise SynthesisError(
            "the saved draft is APPROVED; it cannot be overwritten "
            "(human decision stands)")
    _write(root, draft)
    return draft


def synthesize(root: Path) -> dict:
    """Build and save a fresh deterministic draft."""
    return save_draft(root, build_draft(root))


def _interpretation_prompt(evidence: dict) -> str:
    lines = ["You are assisting a literature review. Below are verbatim",
             "evidence excerpts from approved extraction records. Identify",
             "ONLY: agreements between findings, contradictions between",
             "findings, limitations, and unanswered questions. Cite sources",
             "by their bracketed IDs. Do not invent papers, citations or",
             "findings. If evidence is insufficient, say so.", ""]
    for kind in ("findings", "claims", "methods"):
        for entry in evidence.get(kind, []):
            lines.append(f"[{entry['source_id']}] {entry['text']}")
    return "\n".join(lines)


def add_ai_interpretation(root: Path, draft: dict, provider,
                          task: str = TASK) -> dict:
    """Explicitly request AI interpretation of APPROVED evidence only, via
    RF-014's run_generation(). Result is stored in the separate
    `interpretation` section, labelled AI-GENERATED + PENDING HUMAN REVIEW.
    Provider failures are recorded and marked FAILED — never fabricated."""
    interpretation = draft["interpretation"]
    try:
        response = run_generation(
            provider, ProviderRequest(
                prompt=_interpretation_prompt(draft["evidence"]),
                structured={"format": "json"}), task, root)
    except ProviderError as error:
        interpretation.update({
            "status": "FAILED", "origin": "AI-GENERATED",
            "provider": provider.provider_id, "model": None,
            "error": type(error).__name__,
            "review": REVIEW_PENDING,
        })
        return draft
    try:
        parsed = json.loads(response.content)
        if not isinstance(parsed, dict):
            raise ValueError("interpretation is not a JSON object")
    except (ValueError, TypeError):
        interpretation.update({
            "status": "FAILED", "origin": "AI-GENERATED",
            "provider": provider.provider_id, "model": response.model,
            "error": "unparseable provider response",
            "review": REVIEW_PENDING,
        })
        return draft
    interpretation.update({
        "status": "COMPLETED",
        "origin": "AI-GENERATED",
        "provider": response.provider,
        "model": response.model,
        "error": None,
        "review": REVIEW_PENDING,  # AI text is never auto-approved
    })
    for key in ("agreements", "contradictions", "limitations",
                "unanswered_questions"):
        value = parsed.get(key)
        interpretation[key] = value if isinstance(value, list) else []
    return draft


def approve_synthesis(root: Path, reviewer: str) -> dict:
    """Explicit human approval of the draft. Never automatic."""
    if not reviewer or not reviewer.strip():
        raise SynthesisError("a reviewer name is required for approval")
    draft = load_draft(root)
    if draft is None:
        raise SynthesisError("no synthesis draft exists; run synthesis first")
    draft["review"] = REVIEW_APPROVED
    draft["reviewed_by"] = reviewer.strip()
    draft["reviewed_at"] = _now()
    _write(root, draft)
    approvals.record_decision(root, "synthesis", "literature_review_draft",
                              "APPROVED", reviewer.strip())
    return draft
